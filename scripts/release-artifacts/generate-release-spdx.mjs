#!/usr/bin/env node

import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { hashStableRegularFile } from "./file-integrity.mjs";

function parseArgs(argv) {
  const result = {};
  for (let index = 0; index < argv.length; index += 2) {
    const key = argv[index];
    const value = argv[index + 1];
    if (!key?.startsWith("--") || value === undefined)
      throw new Error(`invalid argument near ${key ?? "<end>"}`);
    const name = key.slice(2);
    if (Object.hasOwn(result, name)) throw new Error(`duplicate --${name}`);
    result[name] = value;
  }
  for (const name of ["root", "manifest", "output"])
    if (!result[name]) throw new Error(`missing --${name}`);
  return result;
}

function spdxId(prefix, value) {
  return `SPDXRef-${prefix}-${createHash("sha256").update(value).digest("hex").slice(0, 24)}`;
}

export function assertArtifactManifest(manifest) {
  if (
    manifest?.schemaVersion !== 2 ||
    manifest.generatedBy !== "release-artifact-material-generator" ||
    !/^[A-Za-z0-9_.-]+\/[A-Za-z0-9_.-]+$/u.test(manifest.repository ?? "") ||
    !/^[0-9a-f]{40}$/u.test(manifest.sourceCommit ?? "") ||
    manifest.sourceRef !== `refs/tags/${manifest.releaseTag}` ||
    !Array.isArray(manifest.assets) ||
    manifest.assets.length === 0
  )
    throw new Error("invalid release artifact manifest");
}

export function buildReleaseSpdx(manifest) {
  assertArtifactManifest(manifest);
  const packageId = spdxId(
    "Package",
    `${manifest.repository}:${manifest.sourceCommit}:${manifest.releaseTag}`,
  );
  const files = manifest.assets.map((asset) => ({
    fileName: asset.filename,
    SPDXID: spdxId("File", `${asset.subjectPath}:${asset.sha256}`),
    checksums: [
      { algorithm: "SHA1", checksumValue: asset.sha1 },
      { algorithm: "SHA256", checksumValue: asset.sha256 },
      {
        algorithm: "SHA512",
        checksumValue: Buffer.from(asset.sha512, "base64").toString("hex"),
      },
    ],
  }));
  const packageVerificationCode = createHash("sha1")
    .update(
      manifest.assets
        .map((asset) => asset.sha1)
        .sort()
        .join(""),
    )
    .digest("hex");
  return {
    spdxVersion: "SPDX-2.3",
    dataLicense: "CC0-1.0",
    SPDXID: "SPDXRef-DOCUMENT",
    name: `SkyTwin desktop ${manifest.releaseTag}`,
    documentNamespace: `https://github.com/${manifest.repository}/releases/tag/${encodeURIComponent(manifest.releaseTag)}/spdx/${manifest.sourceCommit}`,
    creationInfo: {
      created: manifest.created,
      creators: [
        "Organization: SkyTwin",
        "Tool: SkyTwin release artifact material generator",
      ],
    },
    documentDescribes: [packageId],
    packages: [
      {
        name: "SkyTwin desktop release artifacts",
        SPDXID: packageId,
        versionInfo: manifest.appVersion,
        downloadLocation: `https://github.com/${manifest.repository}/releases/tag/${encodeURIComponent(manifest.releaseTag)}`,
        filesAnalyzed: true,
        packageVerificationCode: {
          packageVerificationCodeValue: packageVerificationCode,
        },
        sourceInfo: `Built from Git commit ${manifest.sourceCommit} at ${manifest.sourceRef}.`,
        comment: `Release artifact set for ${manifest.releaseTag}; generated by GitHub Actions run ${manifest.runId}.`,
        externalRefs: [
          {
            referenceCategory: "OTHER",
            referenceType: "vcs",
            referenceLocator: `git+https://github.com/${manifest.repository}.git@${manifest.sourceCommit}`,
          },
        ],
      },
    ],
    files,
    relationships: [
      {
        spdxElementId: "SPDXRef-DOCUMENT",
        relationshipType: "DESCRIBES",
        relatedSpdxElement: packageId,
      },
      ...files.map((file) => ({
        spdxElementId: packageId,
        relationshipType: "CONTAINS",
        relatedSpdxElement: file.SPDXID,
      })),
    ],
  };
}

export function writeReleaseSpdx({ root, manifest, output }) {
  assertArtifactManifest(manifest);
  const absoluteRoot = resolve(root);
  for (const asset of manifest.assets) {
    const observed = hashStableRegularFile(
      absoluteRoot,
      join(absoluteRoot, asset.stagedPath),
    );
    if (
      observed.sha1 !== asset.sha1 ||
      observed.sha256 !== asset.sha256 ||
      observed.sha512 !== asset.sha512 ||
      observed.size !== asset.size
    )
      throw new Error(`${asset.filename} changed before SPDX generation`);
  }
  const document = buildReleaseSpdx(manifest);
  writeFileSync(resolve(output), `${JSON.stringify(document, null, 2)}\n`, {
    flag: "wx",
  });
  return document;
}

function main() {
  const args = parseArgs(process.argv.slice(2));
  const manifest = JSON.parse(readFileSync(resolve(args.manifest), "utf8"));
  writeReleaseSpdx({ root: args.root, manifest, output: args.output });
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
)
  main();
